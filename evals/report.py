"""Render EVALS.md from evals/results/*.json plus thresholds.yaml.

EVALS.md is GENERATED. No number in it is hand-typed next to a result, and the
sha of the thresholds file it was generated against is printed at the top, so
"the thresholds were fixed before the run" is checkable with
`git log --follow evals/thresholds.yaml`.

Usage:
  python -m evals.report --results evals/results --out EVALS.md
"""

from __future__ import annotations

import argparse
import json
import statistics
import subprocess
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
THRESHOLDS = ROOT / "evals" / "thresholds.yaml"


def thresholds_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%H", "--", "evals/thresholds.yaml"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        return (out.stdout or "").strip()[:12] or "uncommitted"
    except OSError:
        return "unknown"


def load_runs(results: Path) -> list[dict[str, Any]]:
    runs = []
    for path in sorted(results.glob("run-*.json")):
        runs.append(json.loads(path.read_text(encoding="utf-8")))
    return runs


def _records_by_case(runs: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    by_case: dict[str, list[dict[str, Any]]] = {}
    for run in runs:
        for record in run["records"]:
            by_case.setdefault(record["case_id"], []).append(record)
    return by_case


def _verdict(record: dict[str, Any], judged: dict[str, Any] | None) -> str:
    if record["grade"] == "deterministic":
        return "pass" if record.get("deterministic_pass") else "fail"
    if judged is None:
        return "not-judged"
    return judged.get("verdict", "fail")


def render(runs: list[dict[str, Any]], judged: dict[str, Any], cfg: dict[str, Any]) -> str:
    by_case = _records_by_case(runs)
    n_runs = len(runs)
    lines: list[str] = []

    lines.append("# EVALS.md — measured, not asserted")
    lines.append("")
    lines.append(
        f"Generated by `python -m evals.report` against "
        f"`evals/thresholds.yaml` at commit `{thresholds_sha()}`, which was "
        "committed before any harness capable of producing a result existed "
        "(`git log --follow evals/thresholds.yaml`). Every number below is read "
        "from `evals/results/*.json`; none is hand-typed."
    )
    lines.append("")
    lines.append(f"**Runs:** {n_runs}, executed consecutively so the provider prompt "
                 "cache is a named variance driver rather than an artefact of spacing.")
    lines.append("")

    # --- hard gates -------------------------------------------------------
    lines.append("## Hard gates")
    lines.append("")
    all_records = [r for run in runs for r in run["records"]]
    gate_rows = []
    for name, label in (
        ("citation_validity", "Citation validity"),
        ("pii_leak", "PII leak"),
        ("error_leakage", "Error leakage"),
    ):
        failures = [
            r for r in all_records
            if any(c["name"] == name and not c["passed"] for c in r["checks"])
        ]
        gate_rows.append((label, len(all_records) - len(failures), len(all_records), failures))
    lines.append("| Gate | Passed | Of | Threshold | Result |")
    lines.append("|---|---|---|---|---|")
    for label, ok, total, failures in gate_rows:
        verdict = "**PASS**" if not failures else "**FAIL**"
        lines.append(f"| {label} | {ok} | {total} | 100% | {verdict} |")
        for f in failures[:3]:
            detail = next(c["detail"] for c in f["checks"] if not c["passed"])
            lines.append(f"| ↳ {f['case_id']} run {f['run']} | | | | {detail[:80]} |")
    lines.append("")

    # --- per case ---------------------------------------------------------
    lines.append("## Per case")
    lines.append("")
    lines.append("| Case | Grade | Verdict across runs | Stable | Outcome | Note |")
    lines.append("|---|---|---|---|---|---|")
    unstable: list[str] = []
    for case_id, records in sorted(by_case.items()):
        verdicts = [
            _verdict(r, judged.get(f"{case_id}-r{r['run']}")) for r in records
        ]
        stable = len(set(verdicts)) == 1
        if not stable:
            unstable.append(case_id)
        outcomes = "/".join(sorted({str(r["outcome"]) for r in records}))
        note = ""
        for expected in cfg["golden"].get("expected_failures", []):
            if expected["case"] == case_id:
                note = "**known failure, registered before the run**"
        lines.append(
            f"| {case_id} | {records[0]['grade']} | {' '.join(verdicts)} | "
            f"{'yes' if stable else '**NO**'} | {outcomes} | {note} |"
        )
    lines.append("")
    lines.append(
        f"**Verdict stability:** {'all cases stable' if not unstable else '**' + ', '.join(unstable) + ' flipped**'}"
        f" across {n_runs} run(s). A case that passes twice and fails once is a more "
        "important finding than any spread in milliseconds."
    )
    lines.append("")

    # --- cost and latency -------------------------------------------------
    lines.append("## Cost and latency")
    lines.append("")
    costs = [r["meta"].get("cost_usd", 0.0) for r in all_records if r.get("meta")]
    lats = [r["elapsed_s"] for r in all_records]
    cached = [
        r["meta"]["usage"].get("cached_prompt_tokens", 0)
        for r in all_records
        if r.get("meta", {}).get("usage")
    ]
    prompt = [
        r["meta"]["usage"].get("prompt_tokens", 0)
        for r in all_records
        if r.get("meta", {}).get("usage")
    ]
    if lats:
        ordered = sorted(lats)
        p95_index = max(0, int(round(0.95 * len(ordered))) - 1)
        lines.append("| Metric | Value | Threshold | Result |")
        lines.append("|---|---|---|---|")
        lines.append(
            f"| Max cost per question | US${max(costs, default=0.0):.4f} | "
            f"US${cfg['budget']['cost_per_question_usd']:.2f} | "
            f"{'**PASS**' if max(costs, default=0.0) <= cfg['budget']['cost_per_question_usd'] else '**FAIL**'} |"
        )
        lines.append(f"| p50 latency | {statistics.median(ordered):.2f} s | "
                     f"{cfg['budget']['p50_latency_s']:.1f} s | "
                     f"{'**PASS**' if statistics.median(ordered) <= cfg['budget']['p50_latency_s'] else '**FAIL**'} |")
        lines.append(f"| p95 latency | {ordered[p95_index]:.2f} s | "
                     f"{cfg['budget']['p95_latency_s']:.1f} s | "
                     f"{'**PASS**' if ordered[p95_index] <= cfg['budget']['p95_latency_s'] else '**FAIL**'} |")
        lines.append(f"| max latency | {ordered[-1]:.2f} s | — | — |")
        lines.append("")
        lines.append(
            f"**p95 caveat.** n={len(ordered)}, so the p95 is the "
            f"{p95_index + 1}th value — one or two observations, both of them the "
            "slowest. The 8 s budget is weakly evidenced at this sample size, and "
            "inflating n by folding in the boundary suite would measure different "
            "questions under different conditions."
        )
        lines.append("")
    if prompt and sum(prompt):
        lines.append(
            f"**Cache split.** {sum(cached)} cached of {sum(prompt)} prompt tokens "
            f"({100 * sum(cached) / sum(prompt):.0f}%). Run 1 is largely uncached and "
            "runs 2-3 largely cached, which is why the runs are consecutive."
        )
        lines.append("")

    # --- refusal ----------------------------------------------------------
    lines.append("## Refusal precision and recall")
    lines.append("")
    lines.append(
        "A refusal is `outcome == \"refused\"`. `needs_clarification` is a third "
        "outcome, counted as neither a refusal nor a false one — gs-009 is scored "
        "as neither."
    )
    lines.append("")
    should_refuse = {"gs-008", "gs-010"}
    refused = {r["case_id"] for r in all_records if r["outcome"] == "refused"}
    correct = should_refuse & refused
    lines.append(
        f"**Golden set, reported as a count (n={len(should_refuse)}):** "
        f"{len(correct)} of {len(should_refuse)} correctly refused; "
        f"{len(refused - should_refuse)} false refusals. A percentage off two "
        "samples would be the least honest number in this file, so it is not given."
    )
    lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Render EVALS.md.")
    parser.add_argument("--results", type=Path, default=ROOT / "evals" / "results")
    parser.add_argument("--judged", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=ROOT / "EVALS.md")
    args = parser.parse_args()

    cfg = yaml.safe_load(THRESHOLDS.read_text(encoding="utf-8"))
    runs = load_runs(args.results)
    if not runs:
        print(f"no run-*.json under {args.results}")
        return 1
    judged = (
        json.loads(args.judged.read_text(encoding="utf-8")) if args.judged else {}
    )
    args.out.write_text(render(runs, judged, cfg), encoding="utf-8")
    print(f"wrote {args.out} from {len(runs)} run(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
